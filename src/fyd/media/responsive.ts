/**
 * Item 9 (fyd-execution): honest responsive media at the render seam.
 *
 * Pure module: no node imports, safe in any bundle. Builds <img> props
 * ONLY from variants that exist in the site's media manifest:
 *
 * INV-RM-1: every <img> exposes srcset + sizes built from real manifest
 * variants, width/height for layout stability, loading="lazy" +
 * decoding="async" below the fold. Upscaling is forbidden: no rendered or
 * srcset width may exceed the source asset's recorded width (the
 * derivatives pipeline already guarantees withoutEnlargement; this seam
 * re-checks defensively).
 *
 * INV-RM-2: every rendered media element carries machine-readable
 * provenance: data-provenance (asset digest), data-rights-source, plus
 * intrinsic dimensions. Human-visible credit stays in the figcaption.
 *
 * INV-RM-3: logos use the smallest variant >= 2x the CSS display width
 * (retina-honest); when no variant reaches 2x, the largest available
 * below it; never an upscaled width.
 *
 * Hero fetchpriority="high" is MEASUREMENT-GATED (heroFetchPriority): it
 * is emitted only when the pinned item-11 lab record
 * (src/fyd/perf/lab-harness/pinned.ts) names the hero as the LCP element
 * for that site. No record (or a record naming another element) ->
 * loading="eager" with no priority. The directive is explicit: priority
 * only when measurement supports it.
 */

import type { DisplayMedia } from "./select";
import { PINNED_LAB } from "../perf/lab-harness/pinned";

export interface HonestVariant {
  name: string;
  width: number;
  height: number;
  url: string;
}

export interface ResponsiveImgProps {
  src: string;
  srcSet: string;
  sizes: string;
  width: number;
  height: number;
  loading: "eager" | "lazy";
  decoding: "async";
  fetchPriority?: "high";
  "data-provenance": string;
  "data-rights-source": string;
}

/** Blur placeholders are not content renditions; they never join a srcset. */
function contentVariants(media: DisplayMedia): HonestVariant[] {
  return (media.variants ?? [])
    .filter((v) => !v.name.startsWith("blur"))
    .filter((v) => Number.isFinite(v.width) && v.width > 0 && typeof v.url === "string" && v.url !== "")
    .map((v) => ({ name: v.name, width: v.width, height: v.height, url: v.url }))
    .sort((a, b) => a.width - b.width);
}

/**
 * The honest source width of the asset: the widest recorded variant.
 * The derivatives pipeline never upscales (withoutEnlargement), so every
 * manifest variant is <= the true source width; the widest variant is the
 * tightest honest cap provable from the manifest alone.
 */
export function honestSourceWidth(media: DisplayMedia): number {
  const vs = contentVariants(media);
  if (vs.length === 0) return media.width;
  return Math.max(media.width, ...vs.map((v) => v.width));
}

/**
 * Build <img> props from manifest variants only. `sizes` must describe the
 * layout's real rendered width (callers: derive it from the CSS, do not
 * guess). `eager` for above-the-fold heroes, `lazy` below the fold.
 * `priorityMeasured` is honored ONLY when the caller passes a
 * measurement-backed true (see heroFetchPriority).
 */
export function responsiveImgProps(
  media: DisplayMedia,
  opts: { sizes: string; eager?: boolean; priorityMeasured?: boolean },
): ResponsiveImgProps {
  const cap = honestSourceWidth(media);
  const vs = contentVariants(media).filter((v) => v.width <= cap);
  const srcSet = vs.map((v) => `${v.url} ${v.width}w`).join(", ");
  const props: ResponsiveImgProps = {
    src: media.src,
    srcSet,
    sizes: opts.sizes,
    width: media.width,
    height: media.height,
    loading: opts.eager ? "eager" : "lazy",
    decoding: "async",
    "data-provenance": media.digest,
    "data-rights-source": media.rightsSource,
  };
  if (opts.eager && opts.priorityMeasured) props.fetchPriority = "high";
  return props;
}

/**
 * INV-RM-3 logo discipline: smallest variant >= 2x the CSS display width;
 * else the largest available below it; never an upscaled width. Returns
 * null when no content variant exists (caller renders the typographic
 * fallback, never an invented image).
 */
export function pickLogoVariant(
  variants: HonestVariant[],
  displayWidthCssPx: number,
): HonestVariant | null {
  const vs = variants
    .filter((v) => !v.name.startsWith("blur") && v.width > 0 && !!v.url)
    .sort((a, b) => a.width - b.width);
  if (vs.length === 0) return null;
  const target = displayWidthCssPx * 2;
  const adequate = vs.find((v) => v.width >= target);
  if (adequate) return adequate;
  return vs[vs.length - 1];
}

/**
 * Measurement-gated hero priority: "high" ONLY when the pinned lab record
 * names the hero as the LCP element for this site. Anything else ->
 * undefined (conservative). The record is checked in and regenerated by
 * the item-11 harness; until the browser leg runs, no site has a hero-LCP
 * record and no hero gets priority.
 */
export function heroFetchPriority(siteId: string): "high" | undefined {
  try {
    return PINNED_LAB.heroLcp[siteId] === "hero" ? "high" : undefined;
  } catch {
    return undefined;
  }
}
