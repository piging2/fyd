/**
 * Item 11 (fyd-execution): regenerate pinned.ts + BASELINE.md from a
 * run-lab.sh measurement. Pure node, no dependencies.
 *
 * pinned.ts is the machine-readable record the regression tests read
 * (js-budget, hero-priority-measured). BASELINE.md is the human rollup.
 * Both are honestly labeled LAB-transport until the browser leg runs.
 */

const fs = require("fs");
const path = require("path");

const HARNESS = __dirname;
const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, cur, i, arr) => {
    if (cur.startsWith("--")) acc.push([cur.slice(2), arr[i + 1]]);
    return acc;
  }, []),
);

const jsCopper = parseInt(args["js-copper"], 10);
const jsHappy = parseInt(args["js-happy"], 10);
const cssCopper = parseInt(args["css-copper"], 10);
const cssHappy = parseInt(args["css-happy"], 10);
const browserOk = args["browser-ok"] === "1";
const stamp = args["stamp"] || new Date().toISOString();
const now = new Date().toISOString();

if (![jsCopper, jsHappy, cssCopper, cssHappy].every(Number.isFinite)) {
  console.error("pin.mjs: non-numeric byte counts");
  process.exit(2);
}

const pinnedTs =
  `/**\n` +
  ` * Items 8/9/11 (fyd-execution): the pinned lab record.\n` +
  ` *\n` +
  ` * GENERATED by run-lab.sh (pin.cjs) at ${now} — do not hand-edit.\n` +
  ` * Read by js-budget.test.ts (INV-SC-3 ceiling) and\n` +
  ` * hero-priority-measured.test.ts (INV-RM-1 measurement-gated priority).\n` +
  ` *\n` +
  ` * Label is LAB-transport: curl-measured transfer bytes through the\n` +
  ` * egress proxy, never field/p75 performance.\n` +
  ` */\n` +
  `\n` +
  `export interface PinnedLab {\n` +
  `  label: string;\n` +
  `  measuredAt: string;\n` +
  `  method: string;\n` +
  `  jsBudgetBytes: Record<string, number>;\n` +
  `  jsBudgetCeilingBytes: Record<string, number>;\n` +
  `  heroLcp: Record<string, string | null>;\n` +
  `}\n` +
  `\n` +
  `export const PINNED_LAB: PinnedLab = {\n` +
  `  label: "lab-transport",\n` +
  `  measuredAt: ${JSON.stringify(now)},\n` +
  `  method:\n` +
  `    "curl through http://hatch-egress-proxy:3130 to :3100, fetch page HTML, " +\n` +
  `    "extract every <script src>, sum %{size_download} (identity encoding, " +\n` +
  `    "raw bytes).",\n` +
  `  jsBudgetBytes: {\n` +
  `    "coppersmith-plumbing": ${jsCopper},\n` +
  `    "happy-place": ${jsHappy},\n` +
  `  },\n` +
  `  // Ceiling = this measurement (first post-fix pin, not opinion). Any\n` +
  `  // future increase fails js-budget.test.ts until deliberately re-pinned.\n` +
  `  jsBudgetCeilingBytes: {\n` +
  `    "coppersmith-plumbing": ${jsCopper},\n` +
  `    "happy-place": ${jsHappy},\n` +
  `  },\n` +
  `  // heroLcp[site] === "hero" only when the browser leg measures the hero\n` +
  `  // as the LCP element. null = unmeasured -> no fetchpriority.\n` +
  `  heroLcp: {\n` +
  `    "coppersmith-plumbing": null,\n` +
  `    "happy-place": null,\n` +
  `  },\n` +
  `};\n`;

fs.writeFileSync(path.join(HARNESS, "pinned.ts"), pinnedTs);
console.log("wrote pinned.ts");

const baselineMd =
  `# FYD lab performance baseline\n` +
  `\n` +
  `Label: **LAB-transport** (curl-measured transfer bytes through the egress\n` +
  `proxy). NOT field performance; never p75, never CrUX, never real-user.\n` +
  `\n` +
  `Measured: ${now} (run ${stamp}). Browser leg: ${
    browserOk ? "ran (reports under var/perf/lab/)" : "NOT RUN — no live browser in this environment"
  }.\n` +
  `\n` +
  `Method: fetch page HTML, extract every \`<script src>\` / stylesheet link,\n` +
  `sum \`%{size_download}\` (identity encoding, raw bytes, no compression).\n` +
  `\n` +
  `| Metric (LAB-transport) | coppersmith-plumbing | happy-place |\n` +
  `|---|---|---|\n` +
  `| JS transferred | ${jsCopper} B | ${jsHappy} B |\n` +
  `| CSS transferred | ${cssCopper} B | ${cssHappy} B |\n` +
  `\n` +
  `## Not measured here\n` +
  `\n` +
  `LCP element, LCP, CLS, FCP, long tasks require the browser leg\n` +
  `(driver.cjs via the Pig house browser). Transport timings (TTFB) through\n` +
  `the proxy are single-sample context, not lab vitals.\n` +
  `\n` +
  `## Reading this file\n` +
  `\n` +
  `- \`jsBudgetBytes\` in pinned.ts is the machine-readable record the\n` +
  `  js-budget regression test pins against.\n` +
  `- \`heroLcp\` gates hero fetchpriority (null = unmeasured = no priority).\n` +
  `- A future measurement that moves these numbers must re-run the harness\n` +
  `  and re-pin with evidence (INV-PM-1: no performance-motivated change\n` +
  `  ships without a before/after lab report on both sites).\n`;

fs.writeFileSync(path.join(HARNESS, "BASELINE.md"), baselineMd);
console.log("wrote BASELINE.md");
