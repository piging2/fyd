/**
 * FYD semantic contract digests (Q-C-03).
 *
 * Computes two digests and writes src/fyd/sitespec/contract-digests.ts:
 * - COMPONENT_CATALOG_DIGEST: sha256 over the normalized component registry
 *   source (src/fyd/components/registry.ts). Comments and whitespace are
 *   stripped before hashing so comment-only edits do not rotate the
 *   version; any catalog change does.
 * - THEME_TOKENS_DIGEST: sha256 over the extracted FYDThemeTokens interface
 *   plus every token interface/type it references, in sorted name order.
 *
 * Usage:
 *   node scripts/fyd-contract-digests.mjs          # regenerate the file
 *   node scripts/fyd-contract-digests.mjs --check  # exit 1 when the checked-in
 *                                                  # file is stale (used by tests)
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY = "src/fyd/components/registry.ts";
const TYPES = "src/fyd/sitespec/types.ts";
const OUT = "src/fyd/sitespec/contract-digests.ts";

const TOKEN_DECLS = [
  "FYDTypeScale",
  "FYDSpacingScale",
  "FYDColorSystem",
  "FYDSurfaces",
  "FYDShadows",
  "FYDLayoutTokens",
  "FYDBreakpoints",
  "FYDMediaTokens",
  "FYDMotionTokens",
  "FYDLayoutCharacter",
  "FYDThemeTokens",
];

function sha256Hex(s) {
  return createHash("sha256").update(s, "utf8").digest("hex");
}

/** Strip block/line comments and collapse whitespace (string literals in the
 *  registry hold prose; collapsing interior spaces is acceptable because the
 *  digest only needs to be stable and change-sensitive). */
function normalizeRegistry(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:])\/\/[^\n]*/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** Extract `export interface NAME ...` or `export type NAME = ...;` with brace matching. */
function extractDecl(src, name) {
  const head = new RegExp(`export\\s+(interface\\s+${name}\\b|type\\s+${name}\\b)`);
  const m = head.exec(src);
  if (!m) throw new Error(`declaration not found: ${name}`);
  let i = m.index + m[0].length;
  // skip to the opening brace or equals
  while (i < src.length && src[i] !== "{" && src[i] !== "=") i++;
  if (src[i] === "=") {
    // type alias: read to the terminating semicolon at depth 0
    let depth = 0;
    const start = i;
    for (; i < src.length; i++) {
      const c = src[i];
      if (c === "{" || c === "(" || c === "[") depth++;
      else if (c === "}" || c === ")" || c === "]") depth--;
      else if (c === ";" && depth === 0) {
        return src.slice(m.index, i + 1);
      }
    }
    throw new Error(`unterminated type alias: ${name}`);
  }
  // interface: brace matching from the opening brace
  let depth = 0;
  const start = i;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return src.slice(m.index, i + 1);
    }
  }
  throw new Error(`unterminated interface: ${name}`);
}

function compute() {
  const registrySrc = readFileSync(join(repo, REGISTRY), "utf8");
  const typesSrc = readFileSync(join(repo, TYPES), "utf8");
  const catalogDigest = sha256Hex(normalizeRegistry(registrySrc));
  const tokenBlocks = TOKEN_DECLS.map((n) => extractDecl(typesSrc, n));
  const tokensDigest = sha256Hex(tokenBlocks.join("\n"));
  return { catalogDigest, tokensDigest };
}

function render(d) {
  return `/**
 * GENERATED by scripts/fyd-contract-digests.mjs. Do not edit by hand.
 *
 * Semantic contract digests (Q-C-03). These pin the render contract:
 * - COMPONENT_CATALOG_DIGEST covers the section component registry
 *   (${REGISTRY}); any catalog change rotates it.
 * - THEME_TOKENS_DIGEST covers FYDThemeTokens and its token interfaces
 *   (${TYPES}); any token-shape change rotates it.
 *
 * render-model.ts derives RENDERER_VERSION and DESIGN_TOKEN_VERSION from
 * these digests, so a stale pin is a contract violation, not a silent
 * drift. Regenerate with: node scripts/fyd-contract-digests.mjs
 */
export const COMPONENT_CATALOG_DIGEST = "${d.catalogDigest}";
export const THEME_TOKENS_DIGEST = "${d.tokensDigest}";
export const CONTRACT_DIGEST_SOURCES = {
  registry: "${REGISTRY}",
  types: "${TYPES}",
} as const;
`;
}

const check = process.argv.includes("--check");
const digests = compute();
if (check) {
  const current = readFileSync(join(repo, OUT), "utf8");
  const m1 = current.match(/COMPONENT_CATALOG_DIGEST = "([0-9a-f]+)"/);
  const m2 = current.match(/THEME_TOKENS_DIGEST = "([0-9a-f]+)"/);
  const stale =
    !m1 ||
    !m2 ||
    m1[1] !== digests.catalogDigest ||
    m2[1] !== digests.tokensDigest;
  if (stale) {
    console.error(
      "contract digests are STALE: regenerate with `node scripts/fyd-contract-digests.mjs`",
    );
    console.error(`  catalog: checked-in=${m1?.[1] ?? "missing"} computed=${digests.catalogDigest}`);
    console.error(`  tokens:  checked-in=${m2?.[1] ?? "missing"} computed=${digests.tokensDigest}`);
    process.exit(1);
  }
  console.log("contract digests are current");
} else {
  writeFileSync(join(repo, OUT), render(digests));
  console.log(`wrote ${OUT}`);
  console.log(`  COMPONENT_CATALOG_DIGEST=${digests.catalogDigest}`);
  console.log(`  THEME_TOKENS_DIGEST=${digests.tokensDigest}`);
}

